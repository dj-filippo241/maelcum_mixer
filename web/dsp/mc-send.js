function poke(m, v, i) { m[i] = v; }
function ap(m, i, x, c) {
	let y = 0;
	y = c * (x - peek(m, i + 1)) + peek(m, i);
	poke(m, x, i);
	poke(m, y, i + 1);
	return y;
}
function op1(m, i, x, g) {
	let s = 0, v = 0, lo = 0;
	s = peek(m, i);
	v = (x - s) * g / (1 + g);
	lo = v + s;
	poke(m, lo + v, i);
	return lo;
}
function svhp(m, i, x, g, k) {
	let s1 = 0, s2 = 0, fh = 0, fb = 0, fl = 0;
	s1 = peek(m, i);
	s2 = peek(m, i + 1);
	fh = (x - (k + g) * s1 - s2) / (1 + g * (k + g));
	fb = g * fh + s1;
	fl = g * fb + s2;
	poke(m, g * fh + fb, i);
	poke(m, g * fb + fl, i + 1);
	return fh;
}
